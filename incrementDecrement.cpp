#include <iostream>

using namespace std;

int main(){

    // Increment dan Decrement (Tambah dan kurang secara bertahap)
    // Preincrement dan postincrement

    int a = 5;
    int b = 5;

    cout<< a<<endl;
    a++; // Postincrement
    cout<<a<<endl;

    cout<<b<<endl;
    ++b; // Preincrement
    cout<<b<<endl;

    
    
    return 0;
}